//! Native image-generation subsystem.
//!
//! Ports the frozen image surface of `packages/ai`:
//! - `images-models.ts` → [`provider`] and [`models`] (provider contract,
//!   parts builder, runtime collection with auth application)
//! - `images-api-registry.ts` → [`api_registry`] (api-keyed dispatch)
//! - `image-models.ts` + `image-models.generated.ts` → the built-in catalog
//!   below, loaded from `data/builtin-image-models.json` through
//!   `include_str!` only
//! - `images.ts` → [`generate_images`] (top-level dispatch)
//! - `api/openrouter-images.ts` + `providers/openrouter-images.ts` →
//!   [`openrouter`] (the only built-in adapter)
//!
//! Main integration note: this module is wired into the crate as
//! `pub mod images;` and re-exported by the crate owner after handoff.

