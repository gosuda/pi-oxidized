/** Parse ALL_EVENT_TYPES from the extension-host Rust source; fails closed. */
export function loadLifecycle(hostSource: string): readonly string[] {
	const lifecycle = parseRustConstArray(hostSource, "ALL_EVENT_TYPES");
	if (lifecycle === null) {
		throw new Error(
			"ALL_EVENT_TYPES array not found in crates/pi/src/core/extension_host.rs",
		);
	}
	return lifecycle;
}

/**
 * Byte-compare one committed artifact against its generated form.
 * Returns [] when identical, else one violation naming the first
 * differing line (or the length mismatch).
 */
export function diffArtifact(
	label: string,
	committed: string,
	generated: string,
): string[] {
	if (committed === generated) return [];
	const committedLines = committed.split("\n");
	const generatedLines = generated.split("\n");
	const count = Math.min(committedLines.length, generatedLines.length);
	for (let i = 0; i < count; i++) {
		const a = committedLines[i] ?? "";
		const b = generatedLines[i] ?? "";
		if (a !== b) {
			return [
				`${label}: first differing line ${i + 1}\n  committed: ${a}\n  generated: ${b}`,
			];
		}
	}
	return [
		`${label}: length mismatch — committed ${committedLines.length} lines, generated ${generatedLines.length} lines`,
	];
}

function main(): void {
	const check = process.argv.includes("--check");
	const lifecycle = loadLifecycle(readFileSync(HOST_SOURCE_PATH, "utf8"));
	const framesText = buildFrames(lifecycle);
	const { text: manifestText } = buildManifest(lifecycle);
	if (check) {
		const violations = [
			...diffArtifact("frames.jsonl", readFileSync(FRAMES_PATH, "utf8"), framesText),
			...diffArtifact("witness-manifest.json", readFileSync(MANIFEST_PATH, "utf8"), manifestText),
		];
		if (violations.length > 0) {
			for (const violation of violations) {
				process.stderr.write(`${violation}\n`);
			}
			process.exit(1);
		}
		process.stdout.write("WITNESS_OK\n");
		return;
	}
	writeFileSync(FRAMES_PATH, framesText);
	writeFileSync(MANIFEST_PATH, manifestText);
	process.stdout.write(`WITNESS_OK ${FRAMES_PATH} ${MANIFEST_PATH}\n`);
}

if (import.meta.main) main();
