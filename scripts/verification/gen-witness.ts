/**
 * ARC11 witness generator (issue #168): the single owner of the shared
 * cross-language extension-bridge witness fixtures.
 *
 * Emits:
 *   - packages/pi-tui-protocol/tests/fixtures/frames.jsonl
 *     (provenance `#` header + one JSON frame per line)
 *   - packages/pi-tui-protocol/tests/fixtures/witness-manifest.json
 *     (generator, totalLines, sorted methodKindPairs, ordered
 *     lifecycleDiscriminants, modifierComboKeyEvents)
 *
 * Determinism: literal payload tables only; methodKindPairs sorted; the
 * manifest is rendered with `JSON.stringify(obj, null, "\t") + "\n"`; frames
 * are `\n`-joined with a trailing newline. No clock, environment, or network
 * input. `--check` regenerates in memory, byte-compares both committed
 * artifacts, prints the first differing line, and exits 1 on drift.
 *
 * Payload literals are grounded in their producers:
 *   - crates/pi-ext/src/protocol.rs (envelope, ErrorPayload, ToolUpdate,
 *     ProviderEvent, session/theme wire types)
 *   - crates/pi-ext/src/server.rs (RegistrySnapshot behind the
 *     extensions.load response, command.execute / tool.prepare /
 *     tool.validate / tool.renderHtml / message_update_delta handlers,
 *     callback_timeout_frame)
 *   - crates/pi-ext/src/adapters.rs (tool.prepare/validate/execute request
 *     literals, provider.stream payload assembly and stream_options_wire,
 *     methods::TOOL_CANCEL / PROVIDER_CANCEL)
 *   - crates/pi-ext/src/client.rs cancel_frame (tool.cancel /
 *     provider.cancel control events: id 0 event, payload {"id": <req id>})
 *
 * Lifecycle frames and manifest discriminants are derived from
 * `ALL_EVENT_TYPES` in crates/pi/src/core/extension_host.rs via
 * parseRustConstArray — never retyped here (plan Decision 3).
 */

