/** Representative lifecycle discriminants that also witness correlated res
 * frames. The default hook answer is `{}`. */
const LIFECYCLE_RES_REPS: readonly string[] = [
	"project_trust",
	"message_end",
	"tool_call",
];

/** Discriminant witnessing the callback-deadline error frame
 * (callback_timeout_frame: code "timeout", not retryable). */
const LIFECYCLE_ERROR_REP = "message_update";

/** First id of the 35 lifecycle req frames (after the last gap-surface id). */
const FIRST_LIFECYCLE_ID = 51;

function lifecycleFrames(lifecycle: readonly string[]): readonly FrameSpec[] {
	const frames: FrameSpec[] = [];
	lifecycle.forEach((name, index) => {
		frames.push({
			id: FIRST_LIFECYCLE_ID + index,
			kind: "req",
			method: name,
			payload: { type: name },
		});
	});
	for (const rep of LIFECYCLE_RES_REPS) {
		const index = lifecycle.indexOf(rep);
		if (index < 0) {
			throw new Error(`lifecycle res representative missing from ALL_EVENT_TYPES: ${rep}`);
		}
		frames.push({ id: FIRST_LIFECYCLE_ID + index, kind: "res", method: rep, payload: {} });
	}
	const errorIndex = lifecycle.indexOf(LIFECYCLE_ERROR_REP);
	if (errorIndex < 0) {
		throw new Error(`lifecycle error representative missing from ALL_EVENT_TYPES: ${LIFECYCLE_ERROR_REP}`);
	}
	frames.push({
		id: FIRST_LIFECYCLE_ID + errorIndex,
		kind: "error",
		method: LIFECYCLE_ERROR_REP,
		payload: {
			code: "timeout",
			message: "extension callback exceeded its server-side deadline",
			retryable: false,
		},
	});
	return frames;
}

/** Every witnessed frame, in canonical order: base corpus, gap surfaces,
 * lifecycle reqs in ALL_EVENT_TYPES order, lifecycle res reps, lifecycle error. */
export function allFrames(lifecycle: readonly string[]): readonly FrameSpec[] {
	return [...BASE_SURFACES, ...NEW_SURFACES, ...lifecycleFrames(lifecycle)];
}

/** Serialize the frames.jsonl artifact (provenance header + JSONL frames). */
export function buildFrames(lifecycle: readonly string[]): string {
	const lines = allFrames(lifecycle).map((frame) => JSON.stringify(frame));
	return `${PROVENANCE}\n${lines.join("\n")}\n`;
}

